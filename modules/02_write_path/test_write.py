"""Module 02 — Write Problems: pytest.

Fails against the shipped naive `charge_client_fee` (charges on every retry);
passes once you guard the effect. Do not edit this file.
"""
import importlib.util
from pathlib import Path

from nova.agent import load_document, payment_memo_prompt
from nova.effects import PaymentGateway
from nova.frozen_llm import FrozenLLM
from nova.store import RecordStore

# Load your_fix by absolute path so this module name doesn't collide with
# modules/03_state/your_fix.py in pytest's module cache.
_spec = importlib.util.spec_from_file_location("write_path_your_fix", Path(__file__).parent / "your_fix.py")
_your_fix = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_your_fix)
charge_client_fee = _your_fix.charge_client_fee

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / "fixtures"
CLIENT_ID = "alpha"
PERIOD = "Q1-2026"
AMOUNT = 2500
SOURCE_DOC = "billing_instruction.md"


def _memo(llm: FrozenLLM, attempt: int) -> str:
    doc = load_document(CLIENT_ID, SOURCE_DOC)
    return llm.complete(payment_memo_prompt(CLIENT_ID, PERIOD, doc, attempt))


def test_two_runs_really_produce_different_memos():
    """Sanity: the failure is only meaningful if the agent's output actually varies."""
    llm = FrozenLLM(FIXTURES / "llm_responses")
    assert _memo(llm, 1) != _memo(llm, 2)


def test_retry_charges_the_client_only_once(tmp_path):
    llm = FrozenLLM(FIXTURES / "llm_responses")
    store = RecordStore(tmp_path / "write_test.db")
    store.init_schema()
    gateway = PaymentGateway()

    for attempt in (1, 2):  # the agent runs, then retries
        memo = _memo(llm, attempt)
        charge_client_fee(gateway, store, CLIENT_ID, PERIOD, AMOUNT, memo)

    charged = gateway.charges_for(CLIENT_ID)
    assert len(charged) == 1, (
        f"the client should be charged exactly once across a retry, but the gateway "
        f"applied {len(charged)} charges -- guard the effect before it happens"
    )
